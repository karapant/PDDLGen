#!/usr/bin/env python3
"""Generate PDDL, solve it with OPTIC, and validate the schedule with VAL."""

import argparse
from decimal import Decimal
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
ACTION = re.compile(r"^(\d+(?:\.\d+)?):\s+(\([^\n]+\))\s+\[(\d+(?:\.\d+)?)\]\s*$", re.M)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--planner", required=True, type=Path, help="OPTIC executable")
    parser.add_argument("--validator", required=True, type=Path, help="VAL Validate executable")
    parser.add_argument("--tolerance", type=float, default=0.000001,
                        help="VAL time/numeric tolerance; must be below the planner separation")
    parser.add_argument("--pddl", action="store_true", help="read existing PDDL inputs instead of Turtle")
    parser.add_argument("--timeout", type=float, default=45, help="planner time budget in seconds")
    parser.add_argument("--output", type=Path, default=ROOT / "target/planning")
    parser.add_argument("--domain", type=Path, default=ROOT / "resources/busModel.ttl")
    parser.add_argument("--problem", type=Path, default=ROOT / "resources/busLogistics.ttl")
    parser.add_argument("--jar", type=Path, default=ROOT / "target/asepaper-1.0-SNAPSHOT.jar")
    args = parser.parse_args()
    if args.timeout <= 0 or args.tolerance <= 0:
        parser.error("--timeout and --tolerance must be positive")
    planner = args.planner.resolve(strict=True)
    validator = args.validator.resolve(strict=True)
    domain_input = args.domain.resolve(strict=True)
    problem_input = args.problem.resolve(strict=True)
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    for name in ["schedule.plan", "validation.log"]:
        (output / name).unlink(missing_ok=True)
    domain = output / "domain-file.pddl"
    problem = output / "problem-file.pddl"
    if args.pddl:
        for source, destination in [(domain_input, domain), (problem_input, problem)]:
            if source != destination:
                shutil.copyfile(source, destination)
    else:
        jar = args.jar.resolve(strict=True)
        with (output / "generator.log").open("w") as log:
            subprocess.run(["java", "-jar", str(jar), str(domain_input), str(problem_input)],
                           cwd=output, stdout=log, stderr=subprocess.STDOUT, check=True, timeout=60)
    # OPTIC keeps improving its incumbent, so a time limit is expected even after a solution.
    timed_out = False
    with (output / "planner.log").open("w") as log:
        try:
            result = subprocess.run([str(planner), str(domain), str(problem)], cwd=output,
                                    stdout=log, stderr=subprocess.STDOUT, timeout=args.timeout)
            if result.returncode != 0:
                raise RuntimeError(f"OPTIC exited with {result.returncode}; see {output / 'planner.log'}")
        except subprocess.TimeoutExpired:
            timed_out = True
    log = (output / "planner.log").read_text()
    plans = []
    for block in log.split("; Plan found with metric ")[1:]:
        actions = list(ACTION.finditer(block))
        if actions:
            plans.append(actions)
    if not plans:
        raise RuntimeError(f"No schedule found; see {output / 'planner.log'}"
                           + (" (planner time limit reached)" if timed_out else ""))
    actions = plans[-1]
    makespan = max(Decimal(a[1]) + Decimal(a[3]) for a in actions)
    plan = output / "schedule.plan"
    plan.write_text("; Generated by OPTIC; see validation.log for the VAL verdict\n"
                    + "\n".join(a[0] for a in actions) + "\n")
    result = subprocess.run([str(validator), "-t", str(args.tolerance), "-m", "-v",
                             str(domain), str(problem), str(plan)],
                            cwd=output, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                            text=True, timeout=60)
    (output / "validation.log").write_text(result.stdout)
    # Some VAL builds use exit 0 even when a plan is invalid. Require the positive verdict.
    if result.returncode != 0 or "Plan valid" not in result.stdout:
        raise RuntimeError(f"Schedule failed VAL validation; see {output / 'validation.log'}")
    print(f"VALID schedule: {len(actions)} actions, makespan {makespan} model time units")
    print(f"Schedule: {plan}")
    print(f"Validation: {output / 'validation.log'}")
    if timed_out:
        print("Planner time limit reached after finding a schedule; optimality is not established.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, RuntimeError, subprocess.SubprocessError) as error:
        sys.exit(str(error))
